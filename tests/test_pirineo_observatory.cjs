'use strict';
const assert=require('node:assert/strict');
const O=require('../src/pirineo_observatory.js');
const core={engine:'0.6.1',issued:'2026-11-11T15:00:00Z',fuentes:{aemet_cap:'error: timeout',avisos:'error: offline',cnp:'PERMISSION_UNKNOWN'},fuentes_edad_min:{},avisos:[],obs:[],metar:[],puntos:[{id:'la_molina',modelos:{icon_eu:{T:0,pr24:null,racha24:null}}}],pois:[{id:'la_molina',nombre:'La Molina',zona:'Cerdanya'}],modelos:['icon_eu'],perfil:{sur:[],norte:[]},contexto:{sidecars:{}}};
const series={la_molina:{time:['2026-11-11T15:00','2026-11-11T18:00'],m:{icon_eu:{temperature_2m:[0,null],precipitation:[null,0],wind_gusts_10m:[null,70],cloud_cover:[80,60]}}}};
const d=O.derive(core,series,null,{pointId:'la_molina',model:'icon_eu',k:0});
assert.equal(d.officialOk,false,'offline warnings cannot imply calm');
assert.equal(d.officialState.startsWith('UNKNOWN'),true);
assert.equal(d.current.temperature,0,'real 0 must remain 0');
assert.equal(d.current.rain,null,'missing precipitation cannot turn into zero');
assert.equal(d.current.gust,null);
assert.equal(d.forecastValidated,false);
assert.equal(d.satelliteIntegrated,false);
assert.equal(d.avalancheIntegrated,false);
assert.equal(O.forecast(series,'la_molina','icon_eu',1).rain,0);
assert.equal(O.source('ok',200),'STALE');
assert.equal(O.source('PERMISSION_UNKNOWN',0),'UNKNOWN');
assert.equal(O.source('API falló (Timeout); caché de 45 min',45),'DEGRADED');
assert.equal(O.source('caché 40 min',40),'CACHED');
const now=Date.parse(core.issued);
const official={...core,fuentes:{...core.fuentes,aemet_cap:'ok'},fuentes_edad_min:{aemet_cap:0}};
assert.equal(O.derive(official,series,null,{model:'icon_eu',now}).officialOk,true);
assert.equal(O.derive({...official,fuentes_edad_min:{aemet_cap:241}},series,null,{model:'icon_eu',now}).officialOk,false);
assert.equal(O.derive(official,series,null,{now:now+181*60000}).officialOk,false,'a previously successful source must become stale');
assert.equal(O.derive({...official,issued:'bad'},series,null,{now}).officialOk,false,'unknown issue time cannot certify warning coverage');
const obs={t:'2026-11-11T14:30:00Z',edad_min:30,T:5};
assert.equal(O.liveAge(obs,core.issued,now+60*60000),90);
assert.equal(O.derive({...official,obs:[obs]},series,null,{now:now+61*60000}).observations.length,0,'station ages advance after publication');
assert.equal(O.liveAge({edad_min:20},core.issued,now+60*60000),80);
assert.equal(O.liveAge(obs,'bad',now),null);
assert.equal(O.liveAge({t:'2026-11-11T16:00:00Z'},core.issued,now),null);
assert.equal(O.nearest([{t:'2026-11-11T14:00',cota_copo_m:1300}],'2026-11-11T15:00',2).cota_copo_m,1300);
assert.equal(O.nearest([{t:'2026-11-11T02:00',cota_copo_m:1300}],'2026-11-11T15:00',2),null);
console.log('PASS: mountain evidence, uncertainty and domain separation');